//! Rust DTOs are the source of truth; no Rust source parsing is involved.
use minerva_runtime::{
    codex::*, conversation::*, plugins::PluginInfo, providers::*, sessions::*, shell::*,
    transcript::*, RunHandle, RunMessage, RunSnapshot, StartRunRequest,
};
use ts_rs::TS;

fn declaration<T: TS>() -> String {
    format!(
        "export {}\n",
        T::decl(&ts_rs::Config::default().with_large_int("number"))
    )
}
fn main() {
    let mut output = String::from("// Generated by minerva-contracts. Do not edit; run npm run contracts:generate.\nexport type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n");
    macro_rules! emit { ($($t:ty),* $(,)?) => { $(output.push_str(&declaration::<$t>());)* }; }
    emit!(
        ContentPart,
        ToolCall,
        ToolResult,
        Transcript,
        SessionInfo,
        SessionMessage,
        IntegrationState,
        Turn,
        SessionBaseline,
        SessionEvent,
        RunMessage,
        StartRunRequest,
        RunHandle,
        RunSnapshot,
        RunRequest,
        SessionRunResult,
        Provider,
        ProviderView,
        ProviderInput,
        LoginStatus,
        QuotaWindow,
        CodexStatus,
        CodexModel,
        CodexReply,
        CodexOptions,
        PluginInfo,
        ShellSettings,
        ShellResult
    );
    print!("{output}");
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::{json, Value};

    #[test]
    fn serde_fixtures_preserve_camel_case_null_and_neutral_json() {
        let request = json!({"sessionId":"s","requestId":"r","parentId":null,"message":{"id":"m","text":"hello"},"model":"model","options":{"nested":[true,null,2,"x"]}});
        let dto: StartRunRequest = serde_json::from_value(request.clone()).unwrap();
        assert_eq!(serde_json::to_value(dto).unwrap(), request);
        let baseline = json!({"session":{"id":"s","title":"title","updatedAt":42,"model":null},"messages":[{"id":"m","parentId":null,"role":"user","createdAt":"now","parts":[{"kind":"custom","data":[1,null,false]}],"extensions":{"opaque":null}}],"cursor":7,"activeRun":null});
        let dto: SessionBaseline = serde_json::from_value(baseline.clone()).unwrap();
        assert_eq!(serde_json::to_value(dto).unwrap(), baseline);
        let snapshot =
            json!({"sessionId":"s","runId":"r","status":"running","parts":[],"error":null});
        let dto: RunSnapshot = serde_json::from_value(snapshot.clone()).unwrap();
        assert_eq!(serde_json::to_value(dto).unwrap(), snapshot);
    }

    #[test]
    fn generated_fields_match_serde_fixtures() {
        let declaration = SessionBaseline::decl(&ts_rs::Config::default().with_large_int("number"));
        assert!(declaration.contains("activeRun: RunSnapshot | null"));
        assert!(declaration.contains("cursor: number"));
        let declaration = SessionMessage::decl(&ts_rs::Config::default().with_large_int("number"));
        assert!(declaration.contains("parentId: string | null"));
        assert!(declaration.contains("createdAt: string"));
        assert!(declaration.contains("extensions: Record<string, JsonValue>"));
        assert!(
            ContentPart::decl(&ts_rs::Config::default().with_large_int("number"))
                .contains("data: JsonValue")
        );
        assert!(
            StartRunRequest::decl(&ts_rs::Config::default().with_large_int("number"))
                .contains("options: JsonValue")
        );
        assert!(
            CodexOptions::decl(&ts_rs::Config::default().with_large_int("number"))
                .contains("effort: string | null")
        );
        let status = CodexStatus {
            connected: false,
            account_type: None,
            email: None,
            message: String::new(),
            quota: None,
            quota_error: None,
        };
        let value: Value = serde_json::to_value(status).unwrap();
        for field in ["accountType", "email", "quota", "quotaError"] {
            assert_eq!(value[field], Value::Null);
            assert!(
                CodexStatus::decl(&ts_rs::Config::default().with_large_int("number"))
                    .contains(field)
            );
        }
    }
}
